// Next chorale: in the key of the week (major, then relative minor) if on, skipping
// ones already done; Riemenschneider order (roughly easier first). `skip` = n to pass over.
export function nextChorale(done, kw = null, skip = 0) {
  const inKey = kw ? CHORALES.filter((c) => (c.minor ? c.pc === kw.minorPc : c.pc === kw.pc)) : CHORALES;
  const order = (arr) => [...arr].sort((a, b) => (a.r || 999) - (b.r || 999));
  const pool = order(inKey).filter((c) => !done.has(c.bwv));
  const all = pool.length ? pool : order(CHORALES).filter((c) => !done.has(c.bwv));
  return all.length ? all[skip % all.length] : null;
}

